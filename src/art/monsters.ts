// Regional variants (frost goblins, ogres, the frost wyrm…) recolour these by swapping exact hex
// colours (see world.ts), so each creature keeps its "slot" colours: change them in both places or not at all.

const OL = '#1B140E';
const P = (d: string, fill: string, w = 2.2) => `<path d="${d}" fill="${fill}" stroke="${OL}" stroke-width="${w}" stroke-linejoin="round"/>`;
const F = (d: string, fill: string, op = 1) => `<path d="${d}" fill="${fill}"${op < 1 ? ` opacity="${op}"` : ''}/>`;
const L = (d: string, c: string, w = 1.4) => `<path d="${d}" stroke="${c}" stroke-width="${w}" fill="none" stroke-linecap="round" stroke-linejoin="round"/>`;
/** A limb: an outlined thick stroke. */
const limb = (d: string, c: string, w: number) => `<path d="${d}" stroke="${OL}" stroke-width="${w + 3.2}" stroke-linecap="round" stroke-linejoin="round" fill="none"/><path d="${d}" stroke="${c}" stroke-width="${w}" stroke-linecap="round" stroke-linejoin="round" fill="none"/>`;
const C = (x: number, y: number, r: number, fill: string, w = 1.6) => `<circle cx="${x}" cy="${y}" r="${r}" fill="${fill}" stroke="${OL}" stroke-width="${w}"/>`;
const glow = (x: number, y: number, r: number, c: string, op = 0.3) => `<circle cx="${x}" cy="${y}" r="${r}" fill="${c}" opacity="${op}"/>`;
const shine = (x: number, y: number, r = 0.9) => `<circle cx="${x}" cy="${y}" r="${r}" fill="#FFF"/>`;
const g = (t: string, s: string) => `<g transform="${t}">${s}</g>`;

